// Browser stand-in for the parts of `node:crypto` the server modules use
// (static build only; the import map in the built index.html points here).

const HEX = Array.from({ length: 256 }, (_, i) => i.toString(16).padStart(2, '0'));

function toBase64(bytes) {
  let s = '';
  for (let i = 0; i < bytes.length; i += 0x8000) s += String.fromCharCode.apply(null, bytes.subarray(i, i + 0x8000));
  return btoa(s);
}

class Bytes extends Uint8Array {
  toString(enc) {
    if (enc === 'hex') { let s = ''; for (const b of this) s += HEX[b]; return s; }
    if (enc === 'base64') return toBase64(this);
    if (enc === 'base64url') return toBase64(this).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
    return super.toString();
  }
}

export function randomBytes(n) {
  const b = new Bytes(n);
  globalThis.crypto.getRandomValues(b);
  return b;
}

// Uniform integer in [min, max), like Node's crypto.randomInt.
export function randomInt(min, max) {
  if (max === undefined) { max = min; min = 0; }
  const range = max - min;
  const limit = Math.floor(0x100000000 / range) * range;
  const u = new Uint32Array(1);
  do globalThis.crypto.getRandomValues(u); while (u[0] >= limit);
  return min + (u[0] % range);
}

